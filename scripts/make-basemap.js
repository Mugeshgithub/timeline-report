#!/usr/bin/env node
// Builds src/js/basemap.js from Natural Earth 1:10m GeoJSON (public domain, https://www.naturalearthdata.com).
// Usage: node scripts/make-basemap.js path/to/geojson-folder
// Expects ne_10m_{land,minor_islands,lakes,rivers_lake_centerlines,admin_0_boundary_lines_land,
// admin_1_states_provinces_lines,roads,urban_areas}.geojson (from github.com/nvkelso/natural-earth-vector).
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
const read = n => JSON.parse(fs.readFileSync(path.join(dir, n + '.geojson'), 'utf8')).features;
const FACTOR = 1e4;

// Douglas–Peucker on [lng, lat] points
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, len = dx * dx + dy * dy;
    let best = -1, bi = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = pts[i];
      let t = len ? ((px - ax) * dx + (py - ay) * dy) / len : 0; t = Math.max(0, Math.min(1, t));
      const ex = ax + t * dx - px, ey = ay + t * dy - py, d = ex * ex + ey * ey;
      if (d > best) { best = d; bi = i; }
    }
    if (best > tol * tol) { keep[bi] = 1; stack.push([a, bi], [bi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
// Google polyline encoding of [lat, lng] at 1e-4 degrees
function encode(pts) {
  let out = '', plat = 0, plng = 0;
  const enc = v => { v = v < 0 ? ~(v << 1) : v << 1; let s = ''; while (v >= 0x20) { s += String.fromCharCode((0x20 | (v & 0x1f)) + 63); v >>= 5; } return s + String.fromCharCode(v + 63); };
  for (const [lng, lat] of pts) {
    const la = Math.round(lat * FACTOR), lo = Math.round(lng * FACTOR);
    if (la === plat && lo === plng && out) continue;
    out += enc(la - plat) + enc(lo - plng); plat = la; plng = lo;
  }
  return out;
}
const lines = g => (!g ? [] : g.type === 'LineString' ? [g.coordinates] : g.type === 'MultiLineString' ? g.coordinates : []);
const polys = g => (!g ? [] : g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : []);

function polyLayer(feats, tol, minPts) {
  const out = [];
  feats.forEach(f => polys(f.geometry).forEach(poly => {
    const rings = poly.map(r => simplify(r, tol)).filter(r => r.length >= (minPts || 4));
    if (rings.length) out.push(rings.map(encode));
  }));
  return out;
}
function lineLayer(feats, tol) {
  const out = [];
  feats.forEach(f => lines(f.geometry).forEach(l => { const s = simplify(l, tol); if (s.length >= 2) out.push(encode(s)); }));
  return out;
}

const roads = read('ne_10m_roads').filter(f => /Highway|Beltway|Bypass/.test(f.properties.type) || (f.properties.type === 'Road' && f.properties.scalerank <= 4));
const layers = {
  land: polyLayer(read('ne_10m_land').concat(read('ne_10m_minor_islands')), 0.0012),
  lakes: polyLayer(read('ne_10m_lakes').filter(f => (f.properties.scalerank || 0) <= 9), 0.0012),
  urban: polyLayer(read('ne_10m_urban_areas'), 0.003),
  rivers: lineLayer(read('ne_10m_rivers_lake_centerlines'), 0.002),
  states: lineLayer(read('ne_10m_admin_1_states_provinces_lines'), 0.006),
  countries: lineLayer(read('ne_10m_admin_0_boundary_lines_land'), 0.002),
  roads: lineLayer(roads.filter(f => !/Highway|Beltway|Bypass/.test(f.properties.type)), 0.002),
  highways: lineLayer(roads.filter(f => /Highway|Beltway|Bypass/.test(f.properties.type)), 0.003),
};
const js = `// World base map from Natural Earth 1:10m (public domain, https://www.naturalearthdata.com).
// Polyline-encoded at 1e-4 degrees. Generated by scripts/make-basemap.js.
globalThis.TR = globalThis.TR || {};
globalThis.TR.BASEMAP = ${JSON.stringify(layers)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'js', 'basemap.js'), js);
for (const k in layers) console.log(k.padEnd(10), String(layers[k].length).padStart(6), 'features', (JSON.stringify(layers[k]).length / 1024).toFixed(0).padStart(6), 'KB');
console.log('total', (js.length / 1024 / 1024).toFixed(2), 'MB');
