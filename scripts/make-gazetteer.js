#!/usr/bin/env node
// Builds src/js/gazetteer.js from GeoNames cities15000.txt (CC BY 4.0, https://www.geonames.org).
// Usage: node scripts/make-gazetteer.js path/to/cities15000.txt
const fs = require('fs');
const path = require('path');
const rows = fs.readFileSync(process.argv[2], 'utf8').split('\n').filter(Boolean).map(l => l.split('\t'));
const out = rows.map(r => [r[2].replace(/[|;]/g, ' '), (+r[4]).toFixed(3), (+r[5]).toFixed(3), Math.round((+r[14] || 0) / 1000)].join('|')).join(';');
const js = `// Towns and cities with 15,000+ people, from GeoNames (CC BY 4.0, https://www.geonames.org).\n// name|lat|lng|population in thousands. Generated by scripts/make-gazetteer.js.\nglobalThis.TR = globalThis.TR || {};\nglobalThis.TR.GAZ = ${JSON.stringify(out)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'js', 'gazetteer.js'), js);
console.log(`${rows.length} places, ${(js.length / 1024).toFixed(0)} KB`);
